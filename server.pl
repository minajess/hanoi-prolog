/*  server.pl - Tower of Hanoi backend. Prolog is the logic engine:
      GET  /api/solve?n=N  -> optimal move list, generated by a Prolog DCG
      POST /api/move       -> validates a move against the Hanoi rules in Prolog
    Everything else is served from the "static" folder (the website).
    Towers are lists of disk sizes, BOTTOM first: [3,2,1] = disk 1 on top. */

:- use_module(library(http/thread_httpd)).
:- use_module(library(http/http_dispatch)).
:- use_module(library(http/http_files)).
:- use_module(library(http/http_json)).
:- use_module(library(http/http_parameters)).
:- use_module(library(lists)).

% Remember where the "static" folder is (next to this file).
:- dynamic static_dir/1.
:- prolog_load_context(directory, D),
   directory_file_path(D, static, S),
   assertz(static_dir(S)).

:- http_handler(root(api/solve), solve_handler, []).
:- http_handler(root(api/move),  move_handler,  []).
:- http_handler(root(.),         static_handler, [prefix]).

%% start/0, start/1: launch the web server (default port 8080).
start :- start(8080).
start(Port) :-
    http_server(http_dispatch, [port(Port)]),
    format("Server running. Open http://localhost:~w in your browser.~n", [Port]).

static_handler(Request) :-
    static_dir(Dir),
    http_reply_from_files(Dir, [], Request).

% ---------- The Tower of Hanoi algorithm (pure Prolog) ----------
% hanoi(N, From, To, Via) describes the list of moves as a DCG.
% Move N-1 disks out of the way, move the big disk, move N-1 back on top.
hanoi(0, _, _, _) --> [].
hanoi(N, From, To, Via) -->
    { N > 0, M is N - 1 },
    hanoi(M, From, Via, To),
    [move(From, To)],
    hanoi(M, Via, To, From).

solve_handler(Request) :-
    http_parameters(Request, [n(N, [integer, between(1, 8)])]),
    phrase(hanoi(N, 0, 2, 1), Moves),          % tower 0 -> tower 2, via 1
    length(Moves, Min),
    maplist(move_dict, Moves, Dicts),
    reply_json_dict(_{n: N, minMoves: Min, moves: Dicts}).

move_dict(move(F, T), _{from: F, to: T}).

% ---------- Rule checking ----------
move_handler(Request) :-
    http_read_json_dict(Request, In),
    Towers = In.towers, From = In.from, To = In.to,
    (   try_move(Towers, From, To, New)
    ->  reply_json_dict(_{valid: true, towers: New})
    ;   reason(Towers, From, To, Msg),
        reply_json_dict(_{valid: false, message: Msg})
    ).

% try_move(+Towers, +From, +To, -NewTowers): succeeds only for legal moves.
try_move(Ts, F, T, New) :-
    between(0, 2, F), between(0, 2, T), F \== T,
    nth0(F, Ts, Src), nth0(T, Ts, Dst),
    append(SrcRest, [Disk], Src),               % only the TOP disk moves
    (   Dst == []                               % empty tower: always fine
    ;   last(Dst, Top), Disk < Top              % never larger on smaller
    ),
    append(Dst, [Disk], Dst2),
    replace(Ts, F, SrcRest, T1),
    replace(T1, T, Dst2, New).

replace(List, I, Val, New) :-
    nth0(I, List, _, Rest),
    nth0(I, New, Val, Rest).

reason(_, F, F, 'Pick a different tower to move to.') :- !.
reason(Ts, F, _, 'That tower has no disk to move.') :- nth0(F, Ts, []), !.
reason(_, _, _, 'Invalid: a larger disk cannot go on a smaller disk.').
